import axios from 'axios';

import buildPaginationQueryOpts from '@/shared/sort/sorts';

import { ICategorizacion } from '@/shared/model/categorizacion.model';

const baseApiUrl = 'api/categorizacions';

export default class CategorizacionService {
  public find(id: number): Promise<ICategorizacion> {
    return new Promise<ICategorizacion>((resolve, reject) => {
      axios
        .get(`${baseApiUrl}/${id}`)
        .then(function (res) {
          resolve(res.data);
        })
        .catch(reject);
    });
  }

  public retrieve(paginationQuery?: any): Promise<any> {
    return new Promise<any>((resolve, reject) => {
      axios
        .get(baseApiUrl + `?${buildPaginationQueryOpts(paginationQuery)}`)
        .then(function (res) {
          resolve(res);
        })
        .catch(reject);
    });
  }

  public delete(id: number): Promise<any> {
    return new Promise<any>((resolve, reject) => {
      axios
        .delete(`${baseApiUrl}/${id}`)
        .then(function (res) {
          resolve(res);
        })
        .catch(reject);
    });
  }

  public create(entity: ICategorizacion): Promise<ICategorizacion> {
    return new Promise<ICategorizacion>((resolve, reject) => {
      axios
        .post(`${baseApiUrl}`, entity)
        .then(function (res) {
          resolve(res.data);
        })
        .catch(reject);
    });
  }

  public update(entity: ICategorizacion): Promise<ICategorizacion> {
    return new Promise<ICategorizacion>((resolve, reject) => {
      axios
        .put(`${baseApiUrl}`, entity)
        .then(function (res) {
          resolve(res.data);
        })
        .catch(reject);
    });
  }
}
